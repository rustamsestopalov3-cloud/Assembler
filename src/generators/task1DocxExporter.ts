function h1(text: string): Paragraph {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 280, after: 120 },
    border: { bottom: { color: MAGENTA, space: 4, style: BorderStyle.SINGLE, size: 12 } },
    children: [
      new TextRun({
        text,
        bold: true,
        size: 28,
        color: NAVY,
        font: 'Calibri',
      }),
    ],
  });
}

function h2(text: string): Paragraph {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 200, after: 80 },
    children: [
      new TextRun({
        text,
        bold: true,
        size: 23,
        color: MAGENTA,
        font: 'Calibri',
      }),
    ],
  });
}

function p(text: string, opts?: { boldPrefix?: string; spaceAfter?: number }): Paragraph {
  const children: TextRun[] = [];
  if (opts?.boldPrefix) {
    children.push(
      new TextRun({
        text: opts.boldPrefix,
        bold: true,
        size: 21,
        color: DARK_TEXT,
        font: 'Calibri',
      })
    );
  }
  children.push(
    new TextRun({
      text,
      size: 21,
      color: DARK_TEXT,
      font: 'Calibri',
    })
  );
  return new Paragraph({
    spacing: { before: 40, after: opts?.spaceAfter ?? 100, line: 264 },
    children,
  });
}

function bullet(boldPrefix: string, text: string): Paragraph {
  return new Paragraph({
    bullet: { level: 0 },
    spacing: { before: 30, after: 70, line: 252 },
    children: [
      new TextRun({ text: boldPrefix, bold: true, size: 20, color: DARK_TEXT, font: 'Calibri' }),
      new TextRun({ text, size: 20, color: DARK_TEXT, font: 'Calibri' }),
    ],
  });
}

function callout(title: string, body: string, fill = LAVENDER, accent = NAVY): Paragraph {
  return new Paragraph({
    spacing: { before: 120, after: 140, line: 260 },
    shading: { type: ShadingType.CLEAR, fill },
    border: { left: { color: accent, size: 24, style: BorderStyle.SINGLE, space: 10 } },
    indent: { left: 140, right: 140 },
    children: [
      new TextRun({ text: `${title}: `, bold: true, size: 20, color: accent, font: 'Calibri' }),
      new TextRun({ text: body, size: 20, color: DARK_TEXT, font: 'Calibri' }),
    ],
  });
}

function makeTable(headers: string[], rows: string[][], colWidthsPct?: number[]): Table {
  const headerCells = headers.map((h, i) =>
    new TableCell({
      width: colWidthsPct ? { size: colWidthsPct[i], type: WidthType.PERCENTAGE } : undefined,
      shading: { type: ShadingType.CLEAR, fill: NAVY },
      margins: { top: 90, bottom: 90, left: 110, right: 110 },
      children: [
        new Paragraph({
          alignment: AlignmentType.LEFT,
          children: [new TextRun({ text: h, bold: true, size: 18, color: 'FFFFFF', font: 'Calibri' })],
        }),
      ],
    })
  );

  const bodyRows = rows.map((r, rIdx) =>
    new TableRow({
      children: r.map((cellText, cIdx) =>
        new TableCell({
          width: colWidthsPct ? { size: colWidthsPct[cIdx], type: WidthType.PERCENTAGE } : undefined,
          shading: rIdx % 2 === 1 ? { type: ShadingType.CLEAR, fill: LIGHT_GRAY } : undefined,
          margins: { top: 75, bottom: 75, left: 110, right: 110 },
          children: [
            new Paragraph({
              spacing: { before: 0, after: 0, line: 230 },
              children: [
                new TextRun({
                  text: cellText,
                  bold: cIdx === 0,
                  size: 18,
                  color: DARK_TEXT,
                  font: 'Calibri',
                }),
              ],
            }),
          ],
        })
      ),
    })
  );

  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 6, color: BORDER_COLOR },
      bottom: { style: BorderStyle.SINGLE, size: 6, color: BORDER_COLOR },
      left: { style: BorderStyle.SINGLE, size: 6, color: BORDER_COLOR },
      right: { style: BorderStyle.SINGLE, size: 6, color: BORDER_COLOR },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 4, color: BORDER_COLOR },
      insideVertical: { style: BorderStyle.SINGLE, size: 4, color: BORDER_COLOR },
    },
    rows: [new TableRow({ tableHeader: true, children: headerCells }), ...bodyRows],
  });
}

function makeImageBlock(png: Uint8Array | undefined, widthPx: number, heightPx: number, caption: string): Paragraph[] {
  if (!png || png.byteLength === 0) return [];
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 140, after: 40 },
      children: [
        new ImageRun({
          type: 'png',
          data: png,
          transformation: { width: widthPx, height: heightPx },
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 0, after: 140 },
      children: [
        new TextRun({
          text: caption,
          italics: true,
          size: 17,
          color: MUTED,
          font: 'Calibri',
        }),
      ],
    }),
  ];
}

