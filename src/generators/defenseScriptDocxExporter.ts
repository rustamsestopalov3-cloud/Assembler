interface TextSegment {
  text: string;
  bold?: boolean;
  color?: string;
}

function parseRichSegments(input: string, baseColor = DARK_TEXT): TextSegment[] {
  // Supports **bold** markers for key numbers/phrases so the speaker never loses their place on paper
  const parts = input.split(/(\*\*[^*]+\*\*)/g);
  return parts
    .filter((p) => p.length > 0)
    .map((part) => {
      if (part.startsWith('**') && part.endsWith('**')) {
        return { text: part.slice(2, -2), bold: true, color: NAVY };
      }
      return { text: part, bold: false, color: baseColor };
    });
}

function speechParagraph(text: string, isLast = false): Paragraph {
  const segments = parseRichSegments(text);
  return new Paragraph({
    spacing: { before: 60, after: isLast ? 140 : 100, line: 288 },
    alignment: AlignmentType.LEFT,
    children: segments.map(
      (seg) =>
        new TextRun({
          text: seg.text,
          bold: seg.bold,
          size: 24, // 12 pt — comfortable to read from a printed A4 sheet
          color: seg.color ?? DARK_TEXT,
          font: 'Calibri',
        })
    ),
  });
}

function slideBlock(opts: {
  slideNum: number;
  title: string;
  timing: string;
  cue: string;
  paragraphs: string[];
  accent?: string;
}): Paragraph[] {
  const accent = opts.accent ?? NAVY;
  const headerShade = accent === MAGENTA ? PINK_SOFT : LAVENDER;

  const headerParagraph = new Paragraph({
    keepNext: true,
    spacing: { before: 220, after: 60 },
    shading: { type: ShadingType.CLEAR, fill: headerShade },
    border: {
      left: { color: accent, size: 24, style: BorderStyle.SINGLE, space: 10 },
      bottom: { color: BORDER_COLOR, size: 6, style: BorderStyle.SINGLE, space: 4 },
    },
    indent: { left: 100, right: 100 },
    children: [
      new TextRun({
        text: `СЛАЙД ${opts.slideNum} из 12  ·  ${opts.title}   `,
        bold: true,
        size: 25,
        color: accent,
        font: 'Calibri',
      }),
      new TextRun({
        text: `[${opts.timing}]`,
        bold: true,
        size: 21,
        color: MUTED,
        font: 'Calibri',
      }),
    ],
  });

  const cueParagraph = new Paragraph({
    keepNext: true,
    spacing: { before: 40, after: 80, line: 240 },
    shading: { type: ShadingType.CLEAR, fill: LIGHT_GRAY },
    border: { left: { color: BORDER_COLOR, size: 12, style: BorderStyle.SINGLE, space: 8 } },
    indent: { left: 140, right: 100 },
    children: [
      new TextRun({
        text: 'Что показать на слайде: ',
        bold: true,
        italics: true,
        size: 20,
        color: MUTED,
        font: 'Calibri',
      }),
      new TextRun({
        text: opts.cue,
        italics: true,
        size: 20,
        color: MUTED,
        font: 'Calibri',
      }),
    ],
  });

  const body = opts.paragraphs.map((txt, idx) =>
    speechParagraph(txt, idx === opts.paragraphs.length - 1)
  );

  return [headerParagraph, cueParagraph, ...body];
}

function qaBlock(question: string, answer: string, idx: number): Paragraph[] {
  return [
    new Paragraph({
      keepNext: true,
      spacing: { before: 140, after: 40, line: 260 },
      children: [
        new TextRun({
          text: `${idx}. Вопрос жюри: `,
          bold: true,
          size: 23,
          color: MAGENTA,
          font: 'Calibri',
        }),
        new TextRun({
          text: `«${question}»`,
          bold: true,
          size: 23,
          color: NAVY,
          font: 'Calibri',
        }),
      ],
    }),
    ...parseRichSegments(answer).length
      ? [
          new Paragraph({
            spacing: { before: 20, after: 90, line: 276 },
            indent: { left: 220 },
            border: { left: { color: NAVY, size: 12, style: BorderStyle.SINGLE, space: 10 } },
            children: parseRichSegments(answer).map(
              (seg) =>
                new TextRun({
                  text: seg.text,
                  bold: seg.bold,
                  size: 22,
                  color: seg.color ?? DARK_TEXT,
                  font: 'Calibri',
                })
            ),
          }),
        ]
      : [],
  ];
}

